import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier, AdaBoostClassifier
from sklearn.svm import SVC
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import roc_auc_score, accuracy_score, precision_score, recall_score, f1_score, confusion_matrix
from scipy.stats import ttest_rel  # Import for t-test
import numpy as np

# Load the dataset
file_path = '/content/student Dataset.csv'
df = pd.read_csv(file_path)

# Create Target Column based on assumed criteria
df['mental_health_issues'] = ((df['failures'] > 1) |
                              (df['absences'] > 10) |
                              (df['health'] < 3) |
                              (df['Dalc'] > 2) |
                              (df['Walc'] > 2)).astype(int)

# Drop the original health-related columns as they are now used to create the target
df = df.drop(columns=['failures', 'absences', 'health', 'Dalc', 'Walc'])

# Data Preprocessing
categorical_columns = df.select_dtypes(include=['object']).columns
df_encoded = pd.get_dummies(df, columns=categorical_columns, drop_first=True)

# Define features and target variable
X = df_encoded.drop('mental_health_issues', axis=1)
y = df_encoded['mental_health_issues']

# Initialize models with hyperparameter grids for tuning
models = {
    'Logistic Regression': (LogisticRegression(), {'C': [0.01, 0.1, 1, 10, 100]}),
    'Decision Tree': (DecisionTreeClassifier(), {'max_depth': [2, 4, 6, 8, 10]}),
    'Random Forest': (RandomForestClassifier(), {'n_estimators': [50, 100, 200], 'max_depth': [None, 10, 20]}),
    'SVM': (SVC(probability=True), {'C': [0.1, 1, 10], 'kernel': ['linear', 'rbf']}),
    'Gradient Boosting': (GradientBoostingClassifier(), {'n_estimators': [50, 100, 200], 'learning_rate': [0.01, 0.1, 1]}),
    'AdaBoost': (AdaBoostClassifier(), {'n_estimators': [50, 100, 200], 'learning_rate': [0.01, 0.1, 1]}),
    'K-Nearest Neighbors': (KNeighborsClassifier(), {'n_neighbors': [3, 5, 7, 9]})
}

# To store results
final_results = {model_name: [] for model_name in models.keys()}
hypothetical_results = {model_name: [] for model_name in models.keys()}

# Perform 30 runs with different 80:20 splits for the original dataset
for i in range(30):
    print(f"Run {i+1}/30")
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=i)

    # Standardize the features
    scaler = StandardScaler()
    X_train = scaler.fit_transform(X_train)
    X_test = scaler.transform(X_test)

    for model_name, (model, params) in models.items():
        grid = GridSearchCV(estimator=model, param_grid=params, scoring='roc_auc', cv=5)
        grid.fit(X_train, y_train)

        best_model = grid.best_estimator_
        y_proba = best_model.predict_proba(X_test)[:, 1]

        auc_score = roc_auc_score(y_test, y_proba)

        # Store results for original scenario
        final_results[model_name].append(auc_score)

# Hypothetical Scenario: Remove some features and retrain models
features_to_remove = ['Medu', 'Fedu', 'studytime']  # Example features to remove
X_hypothetical = df_encoded.drop(columns=features_to_remove + ['mental_health_issues'])

# Perform 30 runs with different 80:20 splits for the hypothetical scenario
for i in range(30):
    X_train, X_test, y_train, y_test = train_test_split(X_hypothetical, y, test_size=0.2, random_state=i)

    # Standardize the features
    X_train = scaler.fit_transform(X_train)
    X_test = scaler.transform(X_test)

    for model_name, (model, params) in models.items():
        grid = GridSearchCV(estimator=model, param_grid=params, scoring='roc_auc', cv=5)
        grid.fit(X_train, y_train)

        best_model = grid.best_estimator_
        y_proba = best_model.predict_proba(X_test)[:, 1]

        auc_score = roc_auc_score(y_test, y_proba)

        # Store results for hypothetical scenario
        hypothetical_results[model_name].append(auc_score)

# Plot Gaussian Distribution (ROC-AUC) with PDF line for each model
for model_name in models.keys():
    plt.figure(figsize=(8, 5))
    sns.histplot(final_results[model_name], kde=True, bins=10, color='blue', stat="density")
    plt.title(f'Gaussian Distribution of ROC-AUC Scores for {model_name} (Original Scenario)')
    plt.xlabel('ROC-AUC Score')
    plt.ylabel('Density')
    plt.show()

# T-test and p-value calculation between original and hypothetical ROC-AUC scores
p_values = {}
for model_name in models.keys():
    t_stat, p_val = ttest_rel(final_results[model_name], hypothetical_results[model_name])
    p_values[model_name] = p_val
    print(f"{model_name} - T-test p-value: {p_val:.4f}")

# Plot p-values for each model
plt.figure(figsize=(10, 6))
sns.barplot(x=list(p_values.keys()), y=list(p_values.values()), palette='Blues')
plt.axhline(0.05, color='red', linestyle='--', label='Significance Threshold (0.05)')
plt.title('T-test p-values for Original vs Hypothetical ROC-AUC Scores')
plt.ylabel('p-value')
plt.xlabel('Model')
plt.xticks(rotation=45)
plt.legend()
plt.show()

# Print p-values for reference
print("\nT-test p-values for each model:")
for model, p_val in p_values.items():
    print(f"{model}: {p_val:.4f}")

# Calculate average ROC-AUC scores for all models
average_auc_scores = {model: np.mean(scores) for model, scores in final_results.items()}

# Identify the best model based on average ROC-AUC score
best_model_name = max(average_auc_scores, key=average_auc_scores.get)
print(f"\nThe best model is: {best_model_name} with an average ROC-AUC of {average_auc_scores[best_model_name]:.4f}")

# Train the best model on the full dataset
best_model = GridSearchCV(estimator=models[best_model_name][0], param_grid=models[best_model_name][1], scoring='roc_auc', cv=5)
X_full_scaled = scaler.fit_transform(X)  # Scale the full dataset
best_model.fit(X_full_scaled, y)

# Predict mental health issues using the best model
y_pred_full = best_model.predict(X_full_scaled)

# Convert the predictions (1 = "Yes", 0 = "No") to labels for visualization
prediction_labels = np.where(y_pred_full == 1, 'Yes', 'No')

# Create a bar chart of the predictions
prediction_counts = pd.Series(prediction_labels).value_counts()

# Plot the bar chart
plt.figure(figsize=(6, 4))
sns.barplot(x=prediction_counts.index, y=prediction_counts.values, palette='Blues')
plt.xlabel('Mental Health Issues')
plt.ylabel('Count')
plt.title(f'Mental Health Predictions ("Yes" or "No") using {best_model_name}')
plt.show()

# Print the count of predictions
print("\nPrediction Counts for Mental Health Issues:")
print(prediction_counts)

# Compare original and hypothetical scenario
comparison_results = pd.DataFrame({
    'Original': [np.mean(final_results[model]) for model in models.keys()],
    'Hypothetical': [np.mean(hypothetical_results[model]) for model in models.keys()]
}, index=models.keys())

# Print the comparison of original vs hypothetical ROC-AUC scores
print("\nComparison of ROC-AUC Scores (Original vs Hypothetical Scenario):")
print(comparison_results)

# Plot the comparison
comparison_results.plot(kind='bar', figsize=(10, 5))
plt.xlabel('Model')
plt.ylabel('Average ROC-AUC Score')
plt.title('Comparison of Average ROC-AUC Scores for Original vs Hypothetical Scenarios')
plt.xticks(rotation=45)
plt.show()

