# %matplotlib inline
import matplotlib as mpl
mpl.rcParams['animation.embed_limit'] = 2**64

# Define hyperparameters to tune the model
num_episodes = 10000
max_steps_per_episode = 100
learning_rate = 0.1
discount_factor = 0.95
exploration_rate = 1.0
max_exploration_rate = 1.0
min_exploration_rate = 0.01
exploration_decay_rate = 0.001

# Create the game environment
env = gym.make("Taxi-v3")

# Initialize the Q-table to zeros
num_states = env.observation_space.n
num_actions = env.action_space.n
q_table = np.zeros((num_states, num_actions))

# Train the model
rewards = []
average_rewards = []
successes = []
for episode in range(num_episodes):
    state = env.reset()
    done = False
    total_reward = 0
    exploration_rate = min_exploration_rate + (max_exploration_rate - min_exploration_rate) * np.exp(-exploration_decay_rate * episode)
    #iterating over the max number of iterations.
    for step in range(max_steps_per_episode):
        # Exploration-exploitation trade-off
        if np.random.uniform(0, 1) < exploration_rate:
            action = env.action_space.sample() # Exploration
        else:
            action = np.argmax(q_table[state, :]) # Exploitation

        # Take the action and observe the next state and reward
        next_state, reward, done, info = env.step(action)

        # Modify the reward for successful and incorrect deliveries
        if done and reward == 20:
            reward = 200 # Increase reward for successful delivery
        elif done and reward == -1:
            reward = -100 # Increase penalty for incorrect delivery

        # Update the Q-table
        q_table[state, action] = (1 - learning_rate) * q_table[state, action] + \
            learning_rate * (reward + discount_factor * np.max(q_table[next_state, :]))

        # Update the state and total reward
        state = next_state
        total_reward += reward

        # If the episode is finished
        if done:
            if reward == 200:
                successes.append(1)
            else:
                successes.append(0)
            break

    # Append the total reward to the rewards list
    rewards.append(total_reward)
    average_rewards.append(np.mean(rewards[-10:])) # Track the rolling average of rewards over the last 10 episodes

    # Print the reward obtained every 1000 episodes
    if (episode + 1) % 1000 == 0:
        print("Episode: {}, Reward: {}, Avg. Reward: {}".format(episode+1, total_reward, average_rewards[-1]))

    # Update hyperparameters
    exploration_rate = max(min_exploration_rate, exploration_rate * (1 - exploration_decay_rate)) # Decrease exploration rate over time
    learning_rate = max(0.01, learning_rate * 0.99) # Decrease learning rate over time
#printing average reward
print("Average reward:", np.mean(rewards))
# printing success rate
print("Success rate:", np.mean(successes))

# Close the environment
env.close()

