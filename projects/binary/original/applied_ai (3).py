#import sklearn libraries 
from sklearn.datasets import make_classification
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.tree import DecisionTreeClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier

# Create a dataset for example
X, y = make_classification(n_samples=1000, n_features=10, random_state=42)

# Define the hyperparameters to tune
tree_params = {'max_depth': [2, 3, 4, 5, 6]}
logistic_params = {'C': [0.001, 0.01, 0.1, 1, 10], 'solver': ['newton-cg', 'lbfgs', 'liblinear']}
forest_params = {'max_depth': [2, 3, 4, 5, 6], 'n_estimators': [10, 50, 100, 200, 500]}

# Split the data into training and test sets
X_train, X_test, y_train, y_test = train_test_split(X, y, random_state=42)

# Create the classifiers
tree_clf = DecisionTreeClassifier(random_state=42)
logistic_clf = LogisticRegression(random_state=42)
forest_clf = RandomForestClassifier(random_state=42)

# Perform grid search to find the best hyperparameters
tree_grid = GridSearchCV(tree_clf, tree_params, cv=5)
tree_grid.fit(X_train, y_train)

logistic_grid = GridSearchCV(logistic_clf, logistic_params, cv=5)
logistic_grid.fit(X_train, y_train)

forest_grid = GridSearchCV(forest_clf, forest_params, cv=5)
forest_grid.fit(X_train, y_train)

# Print the best hyperparameters for each classifier
print("Decision Tree Classifier:", tree_grid.best_params_)
print("Logistic Regression:", logistic_grid.best_params_)
print("Random Forest Classifier:", forest_grid.best_params_)