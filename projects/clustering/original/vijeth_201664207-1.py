#function defining silhouette coefficient
def compute_silhouette_coefficient(data, labels):
    n_samples = len(data)
    s = np.zeros(n_samples)
    for i in range(n_samples):
        a_i = np.mean(np.linalg.norm(data[i] - data[labels == labels[i]], axis=1))
        b_i = np.min([np.mean(np.linalg.norm(data[i] - data[labels == j], axis=1)) for j in set(labels) if j != labels[i]])
        s[i] = (b_i - a_i) / max(a_i, b_i) # s=(b-a)/max(a,b)
    return np.mean(s)

#function defining k_means with 100 iterations
def k_means(data, k, max_iter=100):
  
    # random initialisation of k centroids
    centroid = data[np.random.choice(data.shape[0], k, replace=False), :]
    labels = np.zeros(data.shape[0])
    for i in range(max_iter):
        # assign each point to the nearest centroid
        for j in range(data.shape[0]):
            distances = np.linalg.norm(data[j, :] - centroid, axis=1)
            labels[j] = np.argmin(distances)
        # update the centroids
        for l in range(k):
            centroid[l, :] = np.mean(data[labels == l, :], axis=0)
    
    # compute the silhouette coefficient for the final clustering
    silhouette_coefficient = compute_silhouette_coefficient(data, labels)
    
    return labels, centroid, silhouette_coefficient


